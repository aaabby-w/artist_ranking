import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const src=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const notice={classList:{toggle(k,v){notice.error=v;}}};
const dialog={open:true,appendChild(n){n.parent=this;}};
const body={appendChild(n){n.parent=this;}};
const ctx=vm.createContext({$:s=>s==='#toast'?notice:dialog,document:{body},clearTimeout(){},setTimeout(){return 1;}});
vm.runInContext(src.slice(src.indexOf('function toast('),src.indexOf('function store(')),ctx);
ctx.toast('上传失败',true);
assert.equal(notice.parent,dialog);
assert.equal(notice.error,true);
assert.equal(notice.hidden,false);
dialog.open=false;
ctx.toast('保存成功');
assert.equal(notice.parent,body);
assert.equal(notice.error,false);
assert.match(src,/feedback\.setAttribute\("role", "alert"\)/);
console.log('PASS: notice moves into open dialog top layer, returns to page after close, and distinguishes errors');
