import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const nodes=new Map();
const get=s=>{if(!nodes.has(s))nodes.set(s,{hidden:false,setAttribute(k,v){this[k]=v},scrollIntoView(){},close(){}});return nodes.get(s)};
const saved=new Map();
const context=vm.createContext({document:{querySelector:get},localStorage:{getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)},modal(){}});
vm.runInContext(code.slice(code.indexOf('function initAnnouncement()'),code.indexOf('async function init()')),context);
vm.runInContext('initAnnouncement()',context);
get('#announcement-toggle').onclick();
assert.equal(get('#announcement-body').hidden,true);
vm.runInContext('initAnnouncement()',context);
assert.equal(get('#announcement-body').hidden,true);
get('#announcement-close').onclick();
vm.runInContext('initAnnouncement()',context);
assert.equal(get('.campaign-announcement').hidden,true);
vm.runInContext('openAnnouncement()',context);
assert.equal(get('.campaign-announcement').hidden,false);
assert.equal(get('#announcement-body').hidden,false);
assert.equal(get('#announcement-toggle')['aria-expanded'],'true');
assert.equal(/DDL(?!（截止日期）)/.test(code),false);
console.log('PASS: collapse, dismissal persistence, reopen and deadline wording');
