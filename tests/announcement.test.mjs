import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const nodes=new Map();
const get=s=>{if(!nodes.has(s))nodes.set(s,{hidden:false,setAttribute(k,v){this[k]=v},scrollIntoView(){},close(){}});return nodes.get(s)};
const saved=new Map();
const context=vm.createContext({document:{querySelector:get},localStorage:{getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)},modal(){}});
vm.runInContext(code.slice(code.indexOf('function announcementShown()'),code.indexOf('async function init()')),context);
vm.runInContext('initAnnouncement()',context);
get('#announcement-toggle').onclick();
assert.equal(get('#announcement-body').hidden,true);
vm.runInContext('initAnnouncement()',context);
assert.equal(get('#announcement-body').hidden,true);
get('#announcement-close').onclick();
vm.runInContext('initAnnouncement()',context);
assert.equal(get('.campaign-announcement').hidden,true);
vm.runInContext('openAnnouncement()',context);
assert.equal(get('.campaign-announcement').hidden,false);
assert.equal(get('#announcement-body').hidden,false);
assert.equal(get('#announcement-toggle')['aria-expanded'],'true');
assert.equal(/DDL(?!（截止日期）)/.test(code),false);
// Account-modal switch: on/off, synced with the × button, persisted
const sw=get('#announcement-switch');
vm.runInContext('initAnnouncement()',context);
assert.equal(sw['aria-checked'],'true');
vm.runInContext('setAnnouncementShown(false)',context);
assert.equal(get('.campaign-announcement').hidden,true); assert.equal(sw['aria-checked'],'false'); assert.equal(saved.get('guild-announcement-display'),'closed');
vm.runInContext('setAnnouncementShown(true)',context);
assert.equal(get('.campaign-announcement').hidden,false); assert.equal(sw['aria-checked'],'true'); assert.equal(saved.get('guild-announcement-display'),'open');
get('#announcement-close').onclick();
assert.equal(sw['aria-checked'],'false');
saved.set('guild-announcement-display','collapsed'); vm.runInContext('initAnnouncement()',context);
assert.equal(sw['aria-checked'],'true'); assert.equal(get('#announcement-body').hidden,true);
assert.equal(code.includes('打开公告栏'),false);
assert.match(code,/role="switch" id="announcement-switch"/);
assert.match(code,/注册过的邮箱会直接进原来的账号/); assert.doesNotMatch(code,/name="artist_name" required/);
console.log('PASS: collapse, dismissal persistence, reopen, deadline wording, account switch synced with ×, optional nickname');
